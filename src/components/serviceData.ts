  hook: string;

  /**
   * 진료과목을 짧게 설명하는 본문
   */
  desc: string;

  /**
   * public/images/services/
   */
  image: string;

  /**
   * 메인 카드 및 상세페이지에서 사용하는 진료 키워드
   */
